import {
  readFileSync,
  writeFileSync,
  mkdirSync,
  existsSync,
  readdirSync,
} from "node:fs";
import { resolve } from "node:path";
import { readPublicApi, ROOT, slug } from "./lib/public-api.mjs";
import { reconcileMap } from "./lib/figma-contract.mjs";
import ts from "typescript";

const check = process.argv.includes("--check");
const api = readPublicApi();
const usage = JSON.parse(
  readFileSync(resolve(ROOT, "agent/usage.json"), "utf8"),
);
const designOnly = JSON.parse(
  readFileSync(resolve(ROOT, "agent/design-only.json"), "utf8"),
).names;
const outputs = new Map();
const storyExamples = new Map();
for (const file of readdirSync(resolve(ROOT, "components")).filter(
  (f) =>
    f.endsWith(".stories.tsx") &&
    ![
      "interaction-checks.stories.tsx",
      "text-message-editor.stories.tsx",
    ].includes(f),
)) {
  const path = `components/${file}`;
  const source = api.program.getSourceFile(resolve(ROOT, path));
  const imports = new Map();
  for (const statement of source.statements) {
    if (
      !ts.isImportDeclaration(statement) ||
      !statement.importClause?.namedBindings ||
      !ts.isNamedImports(statement.importClause.namedBindings)
    )
      continue;
    for (const specifier of statement.importClause.namedBindings.elements)
      imports.set(
        specifier.name.text,
        (specifier.propertyName ?? specifier.name).text,
      );
  }
  function visit(node) {
    if (ts.isJsxOpeningElement(node) || ts.isJsxSelfClosingElement(node)) {
      const name = imports.get(node.tagName.getText(source));
      if (name)
        storyExamples.set(name, [
          ...new Set([...(storyExamples.get(name) ?? []), path]),
        ]);
    }
    ts.forEachChild(node, visit);
  }
  visit(source);
}
const mapping = reconcileMap(api.map, api.components);
outputs.set("figma.map.json", JSON.stringify(mapping, null, 2) + "\n");
for (const [name, entry] of Object.entries(usage)) {
  if (!api.components.has(name)) throw new Error(`Unknown usage entry ${name}`);
  for (const key of Object.keys(entry))
    if (
      ![
        "kind",
        "prefer",
        "constraints",
        "summary",
        "whenToUse",
        "whenNotToUse",
      ].includes(key)
    )
      throw new Error(
        `Usage cannot override generated interface field ${name}.${key}`,
      );
  if (entry.kind && !["component", "part", "anatomy"].includes(entry.kind))
    throw new Error(`Unknown usage kind ${name}.${entry.kind}`);
}

for (const name of api.components.keys()) {
  const entry = usage[name];
  if (
    !entry?.summary?.trim() ||
    !entry.whenToUse?.length ||
    !entry.whenNotToUse?.length
  )
    throw new Error(`Missing current selection guidance for ${name}`);
}
if (new Set(designOnly).size !== designOnly.length)
  throw new Error("Duplicate design-only name");
for (const name of designOnly)
  if (typeof name !== "string" || api.components.has(name))
    throw new Error(`Invalid design-only name ${name}`);

const manifest = {
  schemaVersion: 1,
  authority:
    "Generated from TypeScript public interfaces. Usage constraints are curated in agent/usage.json. Figma correspondence is not a prop schema.",
  setup: "docs/agent/setup.md",
  design: "docs/agent/design.md",
  workflow: "docs/agent/workflow.md",
  exceptions: "agent/exceptions.json",
  components: [...api.components.values()]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((component) => {
      return {
        ...component,
        props: component.props.filter((p) => !p.inherited),
        inheritedProps: component.props
          .filter((p) => p.inherited)
          .map((p) => p.name),
        ...(component.branches
          ? {
              branches: component.branches.map((branch) =>
                branch.filter((p) => !p.inherited),
              ),
            }
          : {}),
        kind: usage[component.name]?.kind ?? "component",
        status: "implemented; see verification report for tested scope",
        ...usage[component.name],
        reference: `docs/agent/components/${slug(component.name)}.md`,
        stories: storyExamples.get(component.export) ?? [],
      };
    }),
  designOnly: designOnly.map((name) => ({
    name,
    status: "design-only; no public component export",
  })),
};
outputs.set("agent/manifest.json", JSON.stringify(manifest, null, 2) + "\n");
const esc = (s) => String(s).replaceAll("|", "\\|").replaceAll("\n", " ");
const heading =
  "# Jake UI component index\n\nGenerated by `npm run agent:sync`. Read only the selected references.\n\nUse `npm run agent -- search <term>` or `npm run agent -- inspect <export>`.\n\nKinds: component = reusable control/surface; part = requires family composition; anatomy = lower-level presentation or incomplete interaction, not a ready-made control. Read each constraint before use.\n\n";
outputs.set(
  "docs/agent/components.md",
  heading +
    "| Export | Kind | Purpose |\n|---|---|---|\n" +
    manifest.components
      .map(
        (c) =>
          `| [${c.export}](components/${slug(c.name)}.md) | ${c.kind} | ${esc(c.summary)} |`,
      )
      .join("\n") +
    "\n\n## Design-only assets\n\nThese names are not importable components. Compose from the public exports or request an extension.\n\n" +
    manifest.designOnly.map((c) => `- ${c.name}`).join("\n") +
    "\n",
);
for (const c of manifest.components) {
  const lines = [
    `# ${c.export}`,
    "",
    "Generated from TypeScript and agent/usage.json. Regenerate with `npm run agent:sync`.",
    "",
    `Kind: **${c.kind}**. ${c.status}.`,
    "",
    c.summary,
    "",
    "```tsx",
    c.import,
    "```",
    "",
    `[Implementation](../../../${c.source})` +
      (mapping.components[c.name]?.codePath
        ? " · [Figma correspondence](../../../figma.map.json)"
        : " · Code-only component; no Figma correspondence."),
    "",
    "## Usage",
    "",
    ...c.whenToUse.map((t) => `- ${t}`),
    ...(c.prefer ? [`- Prefer: ${c.prefer}.`] : []),
    ...(c.constraints ?? []).map((t) => `- ${t}`),
    "",
    "## Public props",
    "",
    "Types and required fields below are compiler-derived. Default expressions are extracted where explicitly declared; omitted defaults are not a promise of a static value.",
    "",
    "| Prop | Type | Required | Default expression | Contract |",
    "|---|---|---|---|---|",
    ...c.props.map(
      (p) =>
        `| \`${p.name}\` | \`${esc(p.type)}\` | ${p.required ? "yes" : "no"} | ${p.defaultExpression ? "\`" + esc(p.defaultExpression) + "\`" : "source-defined"} | ${esc(p.description ?? "")} |`,
    ),
  ];
  if (c.inheritedProps.length)
    lines.push(
      "",
      `Additional inherited DOM attributes (${c.inheritedProps.length}) are listed in agent/manifest.json; exclusions and types follow the [source interface](../../../${c.source}).`,
    );
  if (c.branches) {
    lines.push(
      "",
      "## Discriminated branches",
      "",
      "Choose one whole branch; do not combine callbacks/values from different branches.",
    );
    for (const [i, branch] of c.branches.entries())
      lines.push(
        "",
        `### Branch ${i + 1}`,
        "",
        ...branch
          .filter((p) => ["mode", "value", "onChange"].includes(p.name))
          .map((p) => `- \`${p.name}${p.required ? "" : "?"}: ${p.type}\``),
      );
  }
  if (c.supportingTypes.length)
    lines.push(
      "",
      "## Supporting types",
      "",
      "Compiler-selected public types referenced by this interface. Use these exact data shapes.",
      "",
      ...c.supportingTypes.flatMap((t) => ["```ts", t.declaration, "```", ""]),
    );
  lines.push(
    "",
    "## Examples",
    "",
    "The following source stories are available in the repository checkout; installed consumers use [the shipped recipes](../recipes.md).",
    "",
    ...c.stories.map((p) => `- \`${p}\` (repository checkout)`),
    "",
    "## Avoid",
    "",
    ...c.whenNotToUse.map((t) => `- ${t}`),
    "",
    "Use [the workflow](../workflow.md) for absent capabilities; do not infer props from Figma variant labels.",
    "",
  );
  outputs.set(c.reference, lines.join("\n"));
}
let failed = false;
for (const [path, content] of outputs) {
  const full = resolve(ROOT, path);
  if (check) {
    if (!existsSync(full) || readFileSync(full, "utf8") !== content) {
      console.error(`STALE ${path}`);
      failed = true;
    }
  } else {
    mkdirSync(resolve(full, ".."), { recursive: true });
    writeFileSync(full, content);
  }
}
if (failed) process.exitCode = 1;
else
  console.log(
    `${check ? "Verified" : "Generated"} ${manifest.components.length} public interfaces, ${manifest.designOnly.length} design-only assets and Figma correspondences.`,
  );
